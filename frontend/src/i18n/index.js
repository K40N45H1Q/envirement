const interpolate = (value, params = {}) => value.replace(/\{(\w+)\}/g, (_, key) => String(params[key] ?? ''))

export const normalizeLanguage = (language) => (language === 'en' ? 'en' : 'ru')

export const translate = (key, params = {}, language = 'ru') => {
  const normalizedLanguage = normalizeLanguage(language)
  const segments = key.split('.')
  const read = (source) => segments.reduce((value, segment) => value?.[segment], source)
  const message = read(messages[normalizedLanguage]) ?? read(messages.ru) ?? key

  return typeof message === 'string' ? interpolate(message, params) : message
}

export const useI18n = () => {
  const uiStore = useUiStore()
  const language = computed(() => normalizeLanguage(uiStore.language))

  const t = (key, params = {}) => translate(key, params, language.value)

  return {
    language,
    t,
  }
}

